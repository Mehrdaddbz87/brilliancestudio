/**
 * Simulates a small async delay so the fallback CMS API behaves like real content fetches.
 */
function delay(ms) {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

/**
 * Returns CMS content for a page slug from the in-repo fallback dataset.
 */
export async function getCmsPage(slug) {
  await delay(20);
  return cmsContent[slug] ?? null;
}

/**
 * Returns CMS content synchronously when a local fallback is needed immediately.
 */
export function getFallbackCmsPage(slug) {
  return cmsContent[slug] ?? null;
}
